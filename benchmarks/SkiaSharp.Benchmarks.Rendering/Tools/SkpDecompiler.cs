	private static readonly Dictionary<byte, string> OpNames = MakeOpMap();

	private static Dictionary<byte, string> MakeOpMap()
	{
		var d = new Dictionary<byte, string>();
		foreach (var (name, code) in KnownOps) d[code] = name;
		return d;
	}

	public static string Decompile(byte[] skpBytes, string className = "DecompiledScene")
	{
		using var stream = new MemoryStream(skpBytes);
		using var reader = new BinaryReader(stream);

		// Header
		var magic = reader.ReadBytes(8);
		if (Encoding.ASCII.GetString(magic) != "skiapict")
			throw new InvalidDataException("Not an .skp file: magic mismatch");
		var version = reader.ReadUInt32();
		var left = reader.ReadSingle();
		var top = reader.ReadSingle();
		var right = reader.ReadSingle();
		var bottom = reader.ReadSingle();
		var trailing = reader.ReadByte();
		if (trailing != 1)
			throw new NotSupportedException($"Trailing byte {trailing} — only SkPictureData (=1) is supported here");

		// Locate the "read" tag with the op stream. Tags are stored little-
		// endian; on disk "read" reads back as 'd','a','e','r'.
		byte[]? opData = null;
		int tagsSeen = 0;
		while (stream.Position < stream.Length && tagsSeen++ < 32)
		{
			var tag = ReadTag(reader);
			var size = reader.ReadUInt32();
			if (tag == "read")
			{
				opData = reader.ReadBytes((int)size);
				break;
			}
			// Skip unknown tag payloads.
			reader.BaseStream.Position += size;
		}
		if (opData is null)
			throw new InvalidDataException("No 'read' tag found — op stream missing");

		// Decode op stream.
		var sb = new StringBuilder();
		sb.AppendLine("// Auto-generated by SkpDecompiler. Reproduces the drawing captured in an");
		sb.AppendLine("// .skp file via SKCanvas calls. Indexed resources (paints, paths, images,");
		sb.AppendLine("// text blobs) are emitted as {resourceTable}[N] placeholders — filling in the");
		sb.AppendLine("// resource tables requires parsing the data buffer, which this decoder");
		sb.AppendLine("// currently punts on.");
		sb.AppendLine("using SkiaSharp;");
		sb.AppendLine("using SkiaSharp.Tests.Visual;");
		sb.AppendLine();
		sb.AppendLine("namespace SkiaSharp.Benchmarks.Rendering.Scenes;");
		sb.AppendLine();
		sb.AppendLine($"public sealed class {className} : ISkiaScene");
		sb.AppendLine("{");
		sb.AppendLine($"\tpublic string Name => \"{className}\";");
		// Uno's Visual.InfiniteClipRect uses ±FLT_MAX/2-ish sentinels for the
		// cull; anything above 8192 on a side isn't a real surface size, so
		// snap to a benchmark-friendly default and note the original.
		var origWidth = right - left;
		var origHeight = bottom - top;
		var infoW = origWidth is > 0 and < 8192 ? (int)Math.Ceiling(origWidth) : 1024;
		var infoH = origHeight is > 0 and < 8192 ? (int)Math.Ceiling(origHeight) : 1024;
		sb.AppendLine($"\t// Original cull: ({left}, {top}, {right}, {bottom}) — snapped to {infoW}x{infoH} for benchmarking.");
		sb.AppendLine($"\tpublic SKImageInfo Info => new({infoW}, {infoH}, SKColorType.Rgba8888, SKAlphaType.Premul);");
		sb.AppendLine();
		sb.AppendLine("\t// Resolve these from the .skp's data-buffer section (out of scope for the");
		sb.AppendLine("\t// current decoder). For a round-trippable scene, replace with concrete");
		sb.AppendLine("\t// SKPaint / SKPath / SKImage / SKTextBlob instances.");
		sb.AppendLine("\tprivate readonly SKPaint[] paintTable = System.Array.Empty<SKPaint>();");
		sb.AppendLine("\tprivate readonly SKPath[] pathTable = System.Array.Empty<SKPath>();");
		sb.AppendLine("\tprivate readonly SKImage[] imageTable = System.Array.Empty<SKImage>();");
		sb.AppendLine("\tprivate readonly SKTextBlob[] textBlobTable = System.Array.Empty<SKTextBlob>();");
		sb.AppendLine();
		sb.AppendLine("\tpublic void Draw(SKCanvas canvas)");
		sb.AppendLine("\t{");

		DecodeOps(opData, sb);

		sb.AppendLine("\t}");
		sb.AppendLine("}");
		sb.AppendLine();
		sb.AppendLine($"// -- header --");
		sb.AppendLine($"// version = {version}");
		sb.AppendLine($"// cull = ({left}, {top}, {right}, {bottom})");
		sb.AppendLine($"// op stream = {opData.Length} bytes");
		return sb.ToString();
	}

	private static string ReadTag(BinaryReader r)
	{
		// Stored little-endian; convert to the human-readable four-char code by
		// reversing the on-disk order.
		var b = r.ReadBytes(4);
		return new string(new[] { (char)b[3], (char)b[2], (char)b[1], (char)b[0] });
	}

	private static void DecodeOps(byte[] opData, StringBuilder sb)
	{
		using var s = new MemoryStream(opData);
		using var r = new BinaryReader(s);
		var indent = "\t\t";
		int saveDepth = 0;

		while (s.Position < s.Length)
		{
			var opStart = s.Position;
			if (s.Length - opStart < 4) break;

			var word = r.ReadUInt32();
			var op = (byte)((word >> 24) & 0xFF);
			var size = (int)(word & 0x00FFFFFF);

			// A size of MASK_24 (0x00FFFFFF) means the real size follows as a
			// separate uint32; not commonly seen for small pictures.
			if (size == 0x00FFFFFF)
				size = r.ReadInt32();

			if (size < 4 || opStart + size > opData.Length)
			{
				sb.AppendLine($"{indent}// malformed op at offset {opStart}: op={op}, size={size}. Stopping.");
				break;
			}

			var endPos = opStart + size;
			var name = OpNames.GetValueOrDefault(op, $"?_op{op}");

			// Decoder body: emit a valid SKCanvas call for the ops we know, else
			// emit a comment with a hex dump of the args.
			switch (name)
			{
				case "SAVE":
					sb.AppendLine($"{indent}canvas.Save();");
					saveDepth++;
					break;
				case "RESTORE":
					sb.AppendLine($"{indent}canvas.Restore();");
					if (saveDepth > 0) saveDepth--;
					break;
				case "TRANSLATE":
				{
					var dx = r.ReadSingle();
					var dy = r.ReadSingle();
					sb.AppendLine($"{indent}canvas.Translate({F(dx)}, {F(dy)});");
					break;
				}
				case "SCALE":
				{
					var sx = r.ReadSingle();
					var sy = r.ReadSingle();
					sb.AppendLine($"{indent}canvas.Scale({F(sx)}, {F(sy)});");
					break;
				}
				case "ROTATE":
				{
					var deg = r.ReadSingle();
					sb.AppendLine($"{indent}canvas.RotateDegrees({F(deg)});");
					break;
				}
				case "SKEW":
				{
					var sx = r.ReadSingle();
					var sy = r.ReadSingle();
					sb.AppendLine($"{indent}canvas.Skew({F(sx)}, {F(sy)});");
					break;
				}
				case "CONCAT44":
				case "SET_M44":
				{
					// SkM44 = 16 floats, column-major.
					var m = new float[16];
					for (var i = 0; i < 16; i++) m[i] = r.ReadSingle();
					var call = name == "SET_M44" ? "SetMatrix" : "Concat";
					sb.AppendLine($"{indent}// {name} (SkM44, column-major):");
					sb.AppendLine($"{indent}canvas.{call}(new SKMatrix44 {{");
					for (var col = 0; col < 4; col++)
					{
						var vals = string.Join(", ", new[] { m[col * 4], m[col * 4 + 1], m[col * 4 + 2], m[col * 4 + 3] });
						sb.AppendLine($"{indent}\t/* col {col} */ {vals},");
					}
					sb.AppendLine($"{indent}}});");
					break;
				}
				case "CLIP_RECT":
				{
					var rect = ReadRect(r);
					var packed = r.ReadUInt32();
					var offsetToRestore = r.ReadUInt32();
					var doAA = (packed & 0x8000_0000) != 0; // approximate: doAA is packed in the top bit historically
					sb.AppendLine($"{indent}canvas.ClipRect({rect}, /* op */ {ClipOpFrom(packed)}, antialias: {doAA.ToString().ToLowerInvariant()});");
					_ = offsetToRestore; // used by playback to short-circuit empty clip regions; not needed for reproduction
					break;
				}
				case "CLIP_RRECT":
				{
					// SkRRect wire form: 4 floats (rect) + 8 floats (radii) = 48 bytes.
					var rect = ReadRect(r);
					var radii = new float[8];
					for (var i = 0; i < 8; i++) radii[i] = r.ReadSingle();
					var packed = r.ReadUInt32();
					var offsetToRestore = r.ReadUInt32();
					sb.AppendLine($"{indent}// CLIP_RRECT rect={rect}, radii=[{string.Join(", ", radii)}]");
					sb.AppendLine($"{indent}using (var rrect = new SKRoundRect()) {{ rrect.SetRectRadii({rect}, new[] {{ new SKPoint({F(radii[0])}, {F(radii[1])}), new SKPoint({F(radii[2])}, {F(radii[3])}), new SKPoint({F(radii[4])}, {F(radii[5])}), new SKPoint({F(radii[6])}, {F(radii[7])}) }}); canvas.ClipRoundRect(rrect, {ClipOpFrom(packed)}); }}");
					_ = offsetToRestore;
					break;
				}
				case "DRAW_PAINT":
				{
					var paintIdx = r.ReadInt32();
					sb.AppendLine($"{indent}canvas.DrawPaint(paintTable[{paintIdx}]);");
					break;
				}
				case "DRAW_CLEAR":
				{
					var color = r.ReadUInt32();
					sb.AppendLine($"{indent}canvas.Clear({SKColorLiteral(color)});");
					break;
				}
				case "DRAW_RECT":
				{
					var paintIdx = r.ReadInt32();
					var rect = ReadRect(r);
					sb.AppendLine($"{indent}canvas.DrawRect({rect}, paintTable[{paintIdx}]);");
					break;
				}
				case "DRAW_OVAL":
				{
					var paintIdx = r.ReadInt32();
					var rect = ReadRect(r);
					sb.AppendLine($"{indent}canvas.DrawOval({rect}, paintTable[{paintIdx}]);");
					break;
				}
				case "DRAW_RRECT":
				{
					var paintIdx = r.ReadInt32();
					var rect = ReadRect(r);
					var radii = new float[8];
					for (var i = 0; i < 8; i++) radii[i] = r.ReadSingle();
					sb.AppendLine($"{indent}using (var rrect = new SKRoundRect()) {{ rrect.SetRectRadii({rect}, new[] {{ new SKPoint({F(radii[0])}, {F(radii[1])}), new SKPoint({F(radii[2])}, {F(radii[3])}), new SKPoint({F(radii[4])}, {F(radii[5])}), new SKPoint({F(radii[6])}, {F(radii[7])}) }}); canvas.DrawRoundRect(rrect, paintTable[{paintIdx}]); }}");
					break;
				}
				case "DRAW_DRRECT":
				{
					var paintIdx = r.ReadInt32();
					// two SkRRects (rect + 8 radii each) = 96 bytes
					sb.AppendLine($"{indent}// DRAW_DRRECT paintIdx={paintIdx}, 2× SkRRect (96 B) — TODO");
					r.BaseStream.Position += 96;
					break;
				}
				case "DRAW_PATH":
				{
					var paintIdx = r.ReadInt32();
					var pathIdx = r.ReadInt32();
					sb.AppendLine($"{indent}canvas.DrawPath(pathTable[{pathIdx}], paintTable[{paintIdx}]);");
					break;
				}
				case "DRAW_POINTS":
				{
					var paintIdx = r.ReadInt32();
					var mode = r.ReadInt32(); // SKPointMode
					var count = r.ReadInt32();
					sb.AppendLine($"{indent}var points_{opStart} = new SKPoint[{count}];");
					for (var i = 0; i < count; i++)
					{
						var x = r.ReadSingle();
						var y = r.ReadSingle();
						sb.AppendLine($"{indent}points_{opStart}[{i}] = new SKPoint({F(x)}, {F(y)});");
					}
					sb.AppendLine($"{indent}canvas.DrawPoints((SKPointMode){mode}, points_{opStart}, paintTable[{paintIdx}]);");
					break;
				}
				case "DRAW_ARC":
				{
					var paintIdx = r.ReadInt32();
					var oval = ReadRect(r);
					var startAngle = r.ReadSingle();
					var sweep = r.ReadSingle();
					var useCenter = r.ReadInt32() != 0;
					sb.AppendLine($"{indent}canvas.DrawArc({oval}, {F(startAngle)}, {F(sweep)}, useCenter: {useCenter.ToString().ToLowerInvariant()}, paintTable[{paintIdx}]);");
					break;
				}
				case "DRAW_PICTURE":
				{
					var picIdx = r.ReadInt32();
					sb.AppendLine($"{indent}// DRAW_PICTURE picIdx={picIdx} — nested SKPicture; not resolved");
					break;
				}
				case "DRAW_TEXT_BLOB":
				{
					var paintIdx = r.ReadInt32();
					var blobIdx = r.ReadInt32();
					var x = r.ReadSingle();
					var y = r.ReadSingle();
					sb.AppendLine($"{indent}canvas.DrawText(textBlobTable[{blobIdx}], {F(x)}, {F(y)}, paintTable[{paintIdx}]);");
					break;
				}
				case "DRAW_IMAGE2":
				{
					var paintIdx = r.ReadInt32();
					var imgIdx = r.ReadInt32();
					var x = r.ReadSingle();
					var y = r.ReadSingle();
					// SKSamplingOptions: 12 bytes (SkFilterMode + SkMipmapMode + SkCubicResampler or flag)
					r.ReadBytes(Math.Min(12, (int)(endPos - s.Position)));
					sb.AppendLine($"{indent}canvas.DrawImage(imageTable[{imgIdx}], {F(x)}, {F(y)}, /* sampling default */ paintTable[{paintIdx}]);");
					break;
				}
				case "DRAW_IMAGE_RECT2":
				{
					var paintIdx = r.ReadInt32();
					var imgIdx = r.ReadInt32();
					var src = ReadRect(r);
					var dst = ReadRect(r);
					// SKSamplingOptions + constraint flag
					r.ReadBytes(Math.Min(16, (int)(endPos - s.Position)));
					sb.AppendLine($"{indent}canvas.DrawImage(imageTable[{imgIdx}], {src}, {dst}, /* sampling */ paintTable[{paintIdx}]);");
					break;
				}
				case "SAVE_LAYER_SAVELAYERREC":
				{
					var flags = r.ReadInt32();
					var hasBounds = (flags & 0x01) != 0;
					var hasPaint = (flags & 0x02) != 0;
					var hasBackdrop = (flags & 0x04) != 0;
					var hasFlags = (flags & 0x08) != 0;
					sb.Append($"{indent}canvas.SaveLayer(in new SKCanvasSaveLayerRec {{");
					if (hasBounds) sb.Append($" Bounds = {ReadRect(r)},");
					if (hasPaint) sb.Append($" Paint = paintTable[{r.ReadInt32()}],");
					if (hasBackdrop) sb.Append($" Backdrop = /* paintTable[{r.ReadInt32()}].ImageFilter */ null,");
					if (hasFlags) sb.Append($" Flags = (SKCanvasSaveLayerRecFlags){r.ReadInt32()},");
					sb.AppendLine(" });");
					saveDepth++;
					break;
				}
				case "FLUSH":
				case "NOOP":
					// No-op / obsolete flush marker. Skip the payload if any.
					break;
				default:
				{
					// Unknown op — emit as a comment with hex dump of args so the
					// caller can see what got skipped.
					var argLen = size - 4;
					var argBytes = argLen > 0 ? r.ReadBytes(Math.Min(argLen, 64)) : System.Array.Empty<byte>();
					sb.AppendLine($"{indent}// op {name} (code {op}), size {size} bytes — not decoded. First {argBytes.Length} args bytes: {Hex(argBytes)}");
					break;
				}
			}

			// Advance to the next op boundary in case the switch didn't consume
			// the full payload (e.g. an unknown op or an op whose args have
			// variable-length tail data).
			if (s.Position != endPos)
			{
				var remaining = endPos - s.Position;
				if (remaining > 0) r.BaseStream.Position += remaining;
				else if (remaining < 0)
					sb.AppendLine($"{indent}// overshot op boundary by {-remaining} bytes — decoder bug for op {name}. Resyncing.");
				s.Position = endPos;
			}
		}
	}

	// Format helpers
	private static string F(float f)
	{
		if (float.IsNaN(f)) return "float.NaN";
		if (float.IsPositiveInfinity(f)) return "float.PositiveInfinity";
		if (float.IsNegativeInfinity(f)) return "float.NegativeInfinity";
		// Print integer-valued floats as ints for readability.
		return f == (int)f
			? ((int)f).ToString(System.Globalization.CultureInfo.InvariantCulture) + "f"
			: f.ToString("G9", System.Globalization.CultureInfo.InvariantCulture) + "f";
	}

	private static SKRect ReadRectStruct(BinaryReader r)
		=> new(r.ReadSingle(), r.ReadSingle(), r.ReadSingle(), r.ReadSingle());

	private static string ReadRect(BinaryReader r)
	{
		var rect = ReadRectStruct(r);
		return $"new SKRect({F(rect.Left)}, {F(rect.Top)}, {F(rect.Right)}, {F(rect.Bottom)})";
	}

	private static string SKColorLiteral(uint c)
	{
		var a = (byte)((c >> 24) & 0xFF);
		var rc = (byte)((c >> 16) & 0xFF);
		var g = (byte)((c >> 8) & 0xFF);
		var b = (byte)(c & 0xFF);
		return $"new SKColor(0x{rc:X2}, 0x{g:X2}, 0x{b:X2}, 0x{a:X2})";
	}

	private static string ClipOpFrom(uint packed)
	{
		// packed layout differs by picture version; the low bits encode
		// SkRegion::Op (Difference=0, Intersect=1, Union=2, XOR=3, ReverseDifference=4, Replace=5).
		// SKClipOp only has {Difference=0, Intersect=1}. Everything else falls back to Intersect
		// with a comment so the C# compiles.
		var opBits = (int)(packed & 0x0F);
		return opBits switch
		{
			0 => "SKClipOperation.Difference",
			1 => "SKClipOperation.Intersect",
			_ => $"/* raw region-op {opBits} — approximated */ SKClipOperation.Intersect",
		};
	}

	private static string Hex(byte[] b)
	{
		var sb = new StringBuilder(b.Length * 3);
		foreach (var x in b) { sb.Append(x.ToString("x2")); sb.Append(' '); }
		return sb.ToString().TrimEnd();
	}
}
