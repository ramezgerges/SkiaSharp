using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace SkiaSharp.Benchmarks.Rendering.Tools;

/// <summary>
/// Parses an <c>.skp</c> file (Skia picture stream) and emits equivalent C#
/// source code that reconstructs the drawing via <see cref="SKCanvas"/> calls.
///
/// <para>
/// This is a hand-written parser for the format defined in
/// <c>externals/skia/src/core/SkPicture.cpp</c> and <c>SkPictureFlat.h</c>:
/// </para>
///
/// <code>
///   magic "skiapict"      8 bytes
///   version              uint32 LE
///   cull rect            4 × float32 LE
///   trailing byte        1 (=1 for SkPictureData)
///   tag stream:
///     each tag is a big-endian FourCC as read (bytes stored little-endian, so
///     "read" reads back as 'd','a','e','r' on disk), followed by uint32 size.
///     Known tags: read (op stream), fact, tpfc, aray, pctr, draw, eof
///   op stream inside "read":
///     each op word: uint32 LE, high byte = DrawType (SkPictureFlat.h), low 24
///     bits = total byte size of this op including the op word. Args follow.
/// </code>
///
/// <para>
/// The op-stream decoder handles the common ops encountered in Uno / typical
/// UI captures; ops it doesn't recognise are emitted as commented-out hex
/// dumps so the caller can tell what got skipped. Indexed resources (paints,
/// paths, images, text blobs) are emitted as <c>paintTable[N]</c> etc. —
/// filling in the resource tables from the picture's data-buffer section is
/// left to a follow-up (the format is another rabbit hole; see
/// <c>SkPictureData::flattenToBuffer</c>).
/// </para>
/// </summary>
public static class SkpDecompiler
{
	// DrawType enum from externals/skia/src/core/SkPictureFlat.h — kept as a
	// name→code map so the emitted C# is human-readable even when we don't
	// (yet) understand an op's payload.
